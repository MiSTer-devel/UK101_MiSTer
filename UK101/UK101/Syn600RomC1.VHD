-- SYN600 disk monitor ROM for the OSI C1P (machine_type=2), rebuilt
-- 2026-07-21 to fix an instant hang on the "D" (disk boot) command.
--
-- BACKGROUND: the first build of this file was taken verbatim from the user's
-- archived syn600/c1.rom (that folder's makeroms.bat output). Disassembly during hardware bring-up
-- revealed c1.rom is a mislabelled hybrid: its makeroms.bat recipe fills the
-- $FF00 (prompt/dispatch) and $FD00/$FE00 (key/monitor) pages with the *C2*
-- variants (c2_hdm_FF00 / c2_key / c2_65v). Those pages do console I/O through
-- the C2 system ACIA at $FC00 - which on a C1P is just monitor ROM, no ACIA -
-- so the H/D/M prompt could paint (it writes screen RAM directly) but keyboard
-- and disk-boot console I/O were dead, giving the observed immediate hang. It
-- also showed the wrong prompt ("H/D/M", a C2-family boot menu) for a C1.
--
-- FIX: rebuilt from the correct C1 pages, which are exactly synmon.rom's upper
-- half in the same archive: c1_disk_FC00 + c1_key_FD00 + c1_65v_FE00 +
-- c1_dcwm_FF00, mirrored across both 1K halves to fill the 2K ($F800-$FFFF).
--   RESET ($FFFC) -> $FF00, the C1 "D/C/W/M ?" dispatch (console via the C1
--     system ACIA at $F000, keyboard at $DF00 - both correct for this core's
--     machine_type=2 decode).
--   "D" -> JMP $FC00, the C1 disk-boot routine. Verified byte-for-byte
--     IDENTICAL to this core's own CegmonRomC1P $FC00 boot routine (same
--     $C000-$C003 PIA seek, $C010/$C011 ACIA read, index-hole wait, load-and-
--     JMP via ($00fd)) - i.e. the exact code path already confirmed booting
--     OS-65D on real hardware under Cegmon. No disk RTL changes needed.
--   "C"/"W" -> ROM BASIC cold/warm; "M" -> $FE00 65V monitor.
--
-- See SAVE_AND_DISK_PLAN.md (Phase 2, Step 4) for the full disassembly trail.

